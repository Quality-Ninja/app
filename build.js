// Builds the static web app into dist/ (or --out=<folder>): copies src/assets, fills each page's head and header,
// and writes assets/config.js. All configuration is public and comes from the environment; see .env.example.
const fs = require('fs');
const path = require('path');

const option = name => process.argv.find(arg => arg.startsWith(`--${name}=`))?.slice(name.length + 3);
const src = path.join(__dirname, 'src');
const out = path.resolve(__dirname, option('out') || 'dist');
if (path.relative(__dirname, out).startsWith('..') || out === __dirname) throw new Error('--out must be a folder inside app/.');

const trimmed = name => (process.env[name] || '').trim().replace(/\/+$/, '');
const config = {
  apiBaseUrl: trimmed('API_BASE_URL') || 'http://localhost:8000',
  clerkPublishableKey: trimmed('CLERK_PUBLISHABLE_KEY'),
  clerkFrontendApi: trimmed('CLERK_FRONTEND_API'),
};

// Every value lands in HTML attributes and the CSP, so each must be exactly an origin or a publishable key.
for (const name of ['apiBaseUrl', 'clerkFrontendApi']) {
  const value = config[name];
  if (value && (!/^https?:\/\//.test(value) || new URL(value).origin !== value)) throw new Error(`${name} must be an origin such as https://api.example.com, with no path.`);
}
if (config.clerkPublishableKey && !/^pk_(test|live)_[A-Za-z0-9_-]+$/.test(config.clerkPublishableKey)) {
  throw new Error('CLERK_PUBLISHABLE_KEY must be a Clerk publishable key (pk_…). Never put a secret key in the web app.');
}
if (process.env.APP_ENV === 'production' && (!config.apiBaseUrl.startsWith('https://') || !config.clerkFrontendApi.startsWith('https://') || !config.clerkPublishableKey.startsWith('pk_live_'))) {
  throw new Error('Production builds need HTTPS API_BASE_URL and CLERK_FRONTEND_API, and a live Clerk key (pk_live_…).');
}

const clerk = Boolean(config.clerkPublishableKey && config.clerkFrontendApi);
// The policy the API used to send with each page, plus the API origin and blob: images for screenshots.
// frame-ancestors can't be set from a meta tag; render.yaml and serve.js send it as a header.
const csp = [
  "default-src 'self'",
  `script-src 'self'${clerk ? ` ${config.clerkFrontendApi} https://challenges.cloudflare.com https://*.protect.clerk.com` : ''}`,
  `connect-src 'self' ${config.apiBaseUrl}${clerk ? ` ${config.clerkFrontendApi} https://*.protect.clerk.com:*` : ''}`,
  `style-src 'self'${clerk ? " 'unsafe-inline'" : ''}`,
  `img-src 'self' data: blob:${clerk ? ' https://img.clerk.com' : ''}`,
  ...(clerk ? ["worker-src 'self' blob:", 'frame-src https://challenges.cloudflare.com https://*.protect.clerk.com'] : []),
  "base-uri 'none'",
  "form-action 'self'",
].join('; ');
const clerkScripts = clerk ? [
  `<script defer crossorigin="anonymous" src="${config.clerkFrontendApi}/npm/@clerk/ui@1/dist/ui.browser.js"></script>`,
  `<script defer crossorigin="anonymous" data-clerk-publishable-key="${config.clerkPublishableKey}" src="${config.clerkFrontendApi}/npm/@clerk/clerk-js@6/dist/clerk.browser.js"></script>`,
].join('\n  ') : '<!-- Sign-in is not configured: CLERK_PUBLISHABLE_KEY and CLERK_FRONTEND_API are empty. -->';

const partial = name => fs.readFileSync(path.join(src, 'partials', name), 'utf8').trimEnd();
const head = partial('head.html').replace('%CSP%', csp).replace('%CLERK_SCRIPTS%', clerkScripts);
const header = partial('header.html');

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(src, 'assets'), path.join(out, 'assets'), { recursive: true });
fs.writeFileSync(path.join(out, 'assets', 'config.js'), `// Generated by build.js. Public values only.\nwindow.QaNinjaConfig = Object.freeze(${JSON.stringify(config)});\n`);
for (const name of fs.readdirSync(src).filter(name => name.endsWith('.html'))) {
  const html = fs.readFileSync(path.join(src, name), 'utf8').replace('<!-- @head -->', head).replace('<!-- @header -->', header);
  if (/<!-- @|%[A-Z_]+%/.test(html)) throw new Error(`${name} still has an unfilled placeholder.`);
  fs.writeFileSync(path.join(out, name), html);
}
console.log(`Built ${path.relative(__dirname, out)}/ for API ${config.apiBaseUrl}${clerk ? '' : ' (sign-in not configured)'}.`);
